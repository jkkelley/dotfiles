#!/usr/bin/env bash
# md-contents.sh - every Markdown file opens with a contents list.
# Owner order 2026-10-16 UTC: "EVERY .md file starts with content lists at the top".
# Usage: md-contents.sh write|check [--all] [PATH...]   (default: changed .md files vs BASE, else repo root)
#        md-contents.sh global [--check]                (files in config/md-contents-global.list)
#        md-contents.sh discover                        (untracked global .md not yet listed)
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
CONF=${MD_CONTENTS_CONF:-$HERE/../config}
# doctoc is a standard tool, so no TOC generator is written here (Principle 4, never reinvent).
# Pinned by exact version (Rule 15). Its START/END markers make reruns idempotent.
DOCTOC=doctoc@2.5.0
# node:22-slim as of 2026-10-16, pinned by digest (Rule 15)
IMAGE=docker.io/library/node@sha256:c3de60bf2f9dd0ac6370e6117950ff62d6e339527e7472301c9c78a017978392
# maxlevel 3 keeps long docs readable; --notitle because the H1 is already the title.
MAXLEVEL=${MAXLEVEL:-3}
OPTS=(--maxlevel "$MAXLEVEL" --notitle)
BASE=${BASE:-origin/main}
GEN_RE='auto-generated|generated by|generated from|do not (hand-)?edit|never edit'

# Retry 3 times, then report and fail (global automation rule: never loop, never fail silently).
retry() { local n; for n in 1 2 3; do "$@" && return 0; echo "md-contents: attempt $n failed: $*" >&2; sleep 1; done; return 1; }

# doctoc puts a new list at the very top of the file, above the H1, which is not where the owner wants it
# ("starts with content lists at the top" reads as right under the title). doctoc updates in place when its
# markers already exist, so a missing list is seeded as an empty marker pair right after the H1
# (after front matter if there is any), and doctoc fills it. Rejected: moving the block after doctoc runs,
# which would fight doctoc's own rewrite on every rerun.
seed_markers() {
  local f=$1
  grep -q 'START doctoc generated TOC' "$f" && return 0
  awk '
    BEGIN { fm = 0; done = 0 }
    NR == 1 && $0 == "---" { fm = 1; print; next }
    fm == 1 { print; if ($0 == "---") { fm = 2 }; next }
    { print }
    !done && /^# / && !infence { print "\n<!-- START doctoc generated TOC please keep comment here to allow auto update -->\n<!-- END doctoc generated TOC please keep comment here to allow auto update -->"; done = 1 }
    /^```/ { infence = !infence }
    END { if (!done) exit 3 }
  ' "$f" > "$f.seed" && mv "$f.seed" "$f" && return 0
  # No H1: put the list at the top, after front matter, by letting doctoc place it.
  rm -f "$f.seed"
}

# Runs doctoc on absolute-path files. Container when podman exists (Rule 14, same tool in CI and locally);
# npx fallback only for hosts without podman.
run_doctoc() {
  [ "$#" -gt 0 ] || return 0
  local sf; for sf in "$@"; do seed_markers "$sf"; done
  if command -v podman >/dev/null 2>&1; then
    local args=() f
    for f in "$@"; do args+=(-v "$f:$f:Z"); done
    podman run --rm "${args[@]}" "$IMAGE" npx --yes "$DOCTOC" "${OPTS[@]}" "$@" >/dev/null
  else
    npx --yes "$DOCTOC" "${OPTS[@]}" "$@" >/dev/null
  fi
}

# A file is skipped when it matches the exclude config or carries a generated marker in its first 10 lines.
# The doctoc banner itself says "generated TOC", so lines mentioning doctoc are ignored in the marker scan.
excluded() {
  local rel=$1 abs=$2 pat
  shopt -s extglob
  while IFS= read -r pat; do
    case $pat in ''|'#'*) continue;; esac
    # shellcheck disable=SC2254
    case $rel in $pat) return 0;; esac
  done < "$CONF/md-contents.exclude"
  head -10 "$abs" | grep -vi doctoc | grep -qiE "$GEN_RE"
}

# Prints repo-relative .md paths in scope: explicit paths, else changed vs BASE, else all (ALL=1 or --all).
select_files() {
  local root=$1; shift
  if [ "$#" -gt 0 ]; then printf '%s\n' "$@"
  elif [ "${ALL:-0}" = 1 ] || ! git -C "$root" rev-parse --verify -q "$BASE" >/dev/null; then
    git -C "$root" ls-files '*.md'
  else
    { git -C "$root" diff --name-only --diff-filter=AM "$BASE"...HEAD -- '*.md'
      git -C "$root" ls-files -m -o --exclude-standard '*.md'; } | sort -u
  fi
}

cmd_repo() {
  local mode=$1; shift
  [ "${1:-}" = "--all" ] && { ALL=1; shift; }
  local root; root=$(git rev-parse --show-toplevel)
  local files=() rel
  while IFS= read -r rel; do
    [ -f "$root/$rel" ] || continue
    excluded "$rel" "$root/$rel" && continue
    files+=("$root/$rel")
  done < <(select_files "$root" "$@")
  [ "${#files[@]}" -gt 0 ] || { echo "md-contents: nothing in scope"; return 0; }
  apply "$mode" "${files[@]}"
}

# write: doctoc in place. check: doctoc on a copy, any difference means missing or stale.
apply() {
  local mode=$1; shift
  if [ "$mode" = write ]; then
    retry run_doctoc "$@"; echo "md-contents: wrote $# file(s)"; return 0
  fi
  local tmp; tmp=$(mktemp -d)
  local f copies=() bad=0 i=0
  for f in "$@"; do i=$((i+1)); mkdir "$tmp/$i"; cp "$f" "$tmp/$i/x.md"; copies+=("$tmp/$i/x.md"); done
  chmod -R a+rwX "$tmp"
  retry run_doctoc "${copies[@]}"
  i=0
  for f in "$@"; do i=$((i+1)); cmp -s "$f" "$tmp/$i/x.md" || { echo "md-contents: missing or stale contents list: $f" >&2; bad=1; }; done
  rm -rf "$tmp"
  [ "$bad" = 0 ] && echo "md-contents: $# file(s) ok"
  return "$bad"
}

global_paths() {
  local p real
  while IFS= read -r p; do
    case $p in ''|'#'*) continue;; esac
    p=${p/#\~/$HOME}
    [ -f "$p" ] || { echo "md-contents: global file missing, skipped: $p" >&2; continue; }
    real=$(readlink -f "$p")
    # A file inside a git work tree belongs to that repo's own run, not this one.
    if git -C "$(dirname "$real")" rev-parse --is-inside-work-tree >/dev/null 2>&1 \
       && git -C "$(dirname "$real")" ls-files --error-unmatch "$real" >/dev/null 2>&1; then
      echo "md-contents: tracked by a git repo, skipped: $real" >&2; continue
    fi
    echo "$real"
  done < "$CONF/md-contents-global.list" | sort -u
}

cmd_global() {
  local mode=write; [ "${1:-}" = "--check" ] && mode=check
  local files=() f
  while IFS= read -r f; do files+=("$f"); done < <(global_paths)
  if [ "$mode" = write ]; then
    # Timestamped backup before touching files outside any repo (UTC).
    local b; b="$HOME/.local/state/zenith/backup/$(date -u +%Y/%m)/$(date -u +%Y%m%d%H%M%S)-md-contents-global"
    mkdir -p "$b"; for f in "${files[@]}"; do cp -L "$f" "$b/$(echo "$f" | tr / _)"; done
    echo "md-contents: backup in $b"
  fi
  apply "$mode" "${files[@]}"
}

# Lists untracked .md in the usual global locations that the list does not cover.
cmd_discover() {
  local listed f; listed=$(global_paths 2>/dev/null)
  { find "$HOME" -maxdepth 1 -name '*.md'
    find "$HOME/.claude" "$HOME/.codex" "$HOME/.config" "$HOME/.deepseek" -maxdepth 3 -name '*.md' \
      -not -path '*/skills/*' -not -path '*/cache/*' -not -path '*/jobs/*' -not -path '*/node_modules/*' -not -path '*/projects/*' -not -path '*/plugins/*' 2>/dev/null
  } | while IFS= read -r f; do
    f=$(readlink -f "$f")
    grep -qxF "$f" <<<"$listed" || git -C "$(dirname "$f")" ls-files --error-unmatch "$f" >/dev/null 2>&1 || echo "$f"
  done | sort -u
}

case ${1:-} in
  write|check) m=$1; shift; cmd_repo "$m" "$@";;
  global) shift; cmd_global "$@";;
  files) shift; m=$1; shift; apply "$m" "$@";;   # absolute paths, no exclusion (callers decide)
  discover) cmd_discover;;
  *) sed -n 2,6p "$0"; exit 2;;
esac
