#!/usr/bin/env bash
# rolodex: header drafted by scripts/rolodex.py headers - correct any line that is wrong
# name: golden-rules.sh
# purpose: the golden system design rules sit right under every contents list.
# inputs: golden-rules.sh write|check [FILE...]   (default: tracked instruction files of the current repo)
# outputs: stdout, exit code
# writes-to: $HOME/.cache/golden-rules/$name, $HOME/.local/state/zenith/backup, $HOME/.local/state/zenith/golden-rules, $log/repos.tsv, a mktemp scratch path, git branches and PRs
# cleanup: removes its own temp files on exit
# golden-rules.sh - the golden system design rules sit right under every contents list.
# Owner order 2026-10-16 UTC: "they sit right under those content list, blast that shit, I don't care if its
# not dry, i want it wildly known". Repeating the block everywhere is intended, not a DRY violation.
# Usage: golden-rules.sh write|check [FILE...]   (default: tracked instruction files of the current repo)
#        golden-rules.sh global [--check]        (config/golden-rules.global)
#        golden-rules.sh repos [--dry-run]       (one branch + PR per git repo under ~/projects, in parallel)
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
SRC=${GOLDEN_SRC:-$HERE/../claude/golden-rules.md}
CONF=$HERE/../config
MDC=$HERE/md-contents.sh
START='<!-- GOLDEN-RULES:START -->'
END='<!-- GOLDEN-RULES:END -->'
DOCTOC_END='<!-- END doctoc generated TOC please keep comment here to allow auto update -->'
NAMES=(AGENTS.md CLAUDE.md GEMINI.md CLAUDE_TEMPLATE.md)
GEN_RE='auto-generated|generated by|do not (hand-)?edit|never edit'
# Inputs come from env/arguments with these defaults, and Make passes them as VAR=value (Design principles 101 item 17).
BRANCH=${BRANCH:-chore/golden-rules}
PARALLEL=${PARALLEL:-8}
PROJECTS=${PROJECTS:-$HOME/projects}

# Tracked instruction files of a repo. Vendored skill copies are fixed at their source, never in place.
repo_files() {
  local root=$1 n
  for n in "${NAMES[@]}"; do git -C "$root" ls-files "$n" "*/$n"; done \
    | grep -v -e '/skills/synced/' -e 'node_modules/' | sort -u | sed "s|^|$root/|"
}

# Removes any old block (plus the blank line before it), then inserts the current block after the doctoc
# END marker, so a rerun is a no-op. The file is given a contents list first and refreshed after, because
# the block carries headings that belong in the list too: the pair of runs reaches a fixed point.
apply_block() {
  local f=$1 tmp; tmp=$(mktemp)
  bash "$MDC" files write "$f" >/dev/null
  grep -qF "$DOCTOC_END" "$f" || { echo "golden-rules: no contents list in $f" >&2; rm -f "$tmp"; return 1; }
  awk -v start="$START" -v end="$END" -v dend="$DOCTOC_END" -v src="$SRC" '
    { lines[NR] = $0 }
    END {
      n = NR; skip = 0
      for (i = 1; i <= n; i++) {
        if (lines[i] == start) { skip = 1; if (out > 0 && buf[out] == "") out--; continue }
        if (skip) { if (lines[i] == end) skip = 0; continue }
        buf[++out] = lines[i]
        if (lines[i] == dend && !placed) {
          buf[++out] = ""; buf[++out] = start
          while ((getline l < src) > 0) buf[++out] = l
          buf[++out] = end; placed = 1
        }
      }
      for (i = 1; i <= out; i++) print buf[i]
    }' "$f" > "$tmp" && cat "$tmp" > "$f"
  rm -f "$tmp"
  bash "$MDC" files write "$f" >/dev/null
}

# Compares the block between the markers with the source, nothing else.
block_ok() {
  local f=$1
  grep -qF "$START" "$f" || return 1
  diff -q <(sed -n "/^$START\$/,/^$END\$/p" "$f" | sed '1d;$d') "$SRC" >/dev/null
}

skip_file() { head -10 "$1" | grep -vi doctoc | grep -qiE "$GEN_RE"; }

cmd_files() {
  local mode=$1; shift; local f bad=0
  for f in "$@"; do
    [ -f "$f" ] || continue
    [ "${GOLDEN_FORCE:-0}" != 1 ] && skip_file "$f" && { echo "golden-rules: marked generated, skipped: $f" >&2; continue; }
    if [ "$mode" = write ]; then apply_block "$f" || bad=1
    else block_ok "$f" || { echo "golden-rules: missing or drifted block: $f" >&2; bad=1; }; fi
  done
  return "$bad"
}

global_files() {
  local p
  while IFS= read -r p; do
    case $p in ''|'#'*) continue;; esac
    p=${p/#\~/$HOME}; [ -f "$p" ] && readlink -f "$p"
  done < "$CONF/golden-rules.global" | sort -u
}

cmd_global() {
  local mode=write files=() f; [ "${1:-}" = "--check" ] && mode=check
  while IFS= read -r f; do files+=("$f"); done < <(global_files)
  if [ "$mode" = write ]; then
    local b; b="$HOME/.local/state/zenith/backup/$(date -u +%Y/%m)/$(date -u +%Y%m%d%H%M%S)-golden-rules-global"
    mkdir -p "$b"; for f in "${files[@]}"; do cp -L "$f" "$b/$(echo "$f" | tr / _)"; done
    echo "golden-rules: backup in $b"
  fi
  # Files named in the global config were chosen by the owner by name, so a generated marker does not skip them.
  GOLDEN_FORCE=1 cmd_files "$mode" "${files[@]}"
}

# One repo: worktree off the default branch (the owner's checkout is never touched), apply, commit, push, PR.
# Logged as a TSV row. Retry 3 on the network steps, then report the failure in the row.
one_repo() {
  local repo=$1 name wt def url rc=0
  name=$(basename "$repo"); wt="$HOME/.cache/golden-rules/$name"
  row() { printf '%s\t%s\t%s\n' "$name" "$1" "${2:-}"; }
  retry() { local n; for n in 1 2 3; do "$@" && return 0; sleep 2; done; return 1; }
  retry git -C "$repo" fetch -q origin || { row FAIL "fetch"; return 0; }
  def=$(git -C "$repo" symbolic-ref -q --short refs/remotes/origin/HEAD 2>/dev/null | sed 's|^origin/||' || true)
  [ -n "$def" ] || def=$(git -C "$repo" branch -r | grep -oE 'origin/(main|master)$' | head -1 | sed 's|origin/||')
  [ -n "$def" ] || { row FAIL "no default branch"; return 0; }
  [ -z "$(git -C "$repo" ls-tree -r --name-only "origin/$def" | grep -E '(^|/)(AGENTS|CLAUDE|GEMINI|CLAUDE_TEMPLATE)\.md$' || true)" ] && { row SKIP "no instruction files"; return 0; }
  rm -rf "$wt"; git -C "$repo" worktree prune
  git -C "$repo" worktree add -q -B "$BRANCH" "$wt" "origin/$def" 2>/dev/null || { row FAIL "worktree"; return 0; }
  # shellcheck disable=SC2046
  GOLDEN_SRC=$SRC cmd_files write $(repo_files "$wt") >/dev/null 2>&1 || rc=$?
  if [ -z "$(git -C "$wt" status --porcelain)" ]; then row SKIP "already current"; git -C "$repo" worktree remove --force "$wt"; return 0; fi
  git -C "$wt" add -A
  git -C "$wt" commit -q -m "docs: golden system design rules under the contents list of agent instruction files" \
    -m "Written by dotfiles scripts/golden-rules.sh from claude/golden-rules.md."
  retry git -C "$wt" push -q -f -u origin "$BRANCH" 2>/dev/null || { row FAIL "push"; return 0; }
  # gh picks the fork parent when a clone has an upstream remote: seen live on ~/projects/firstmate 2026-10-16 UTC,
  # where `gh repo view` resolves to the third-party upstream, so the PR was aimed at someone else's repo and failed
  # as "pr create". The PR always targets origin, the repo the branch was pushed to. Rejected: skipping repos with an
  # upstream remote, which would leave forks without the rules.
  local gr; gr=$(git -C "$repo" remote get-url origin | sed -E 's#^(git@github\.com:|https://github\.com/)##; s#\.git$##')
  url=$(gh pr list -R "$gr" --head "$BRANCH" --state open --json url -q '.[0].url' 2>/dev/null || true)
  [ -n "$url" ] || url=$(gh pr create -R "$gr" --base "$def" --head "$BRANCH" \
    --title "docs: golden system design rules under the contents list of agent instruction files" \
    --body "Adds the golden system design rules block right under the contents list of each agent instruction file (AGENTS.md, CLAUDE.md, GEMINI.md, CLAUDE_TEMPLATE.md).
Generated by the dotfiles golden-rules script from one source file; repeating the block is intended (owner order 2026-10-16 UTC).
Docs only." 2>/dev/null | tail -1) || true
  [ -n "$url" ] && row PR "$url" || row FAIL "pr create"
  git -C "$repo" worktree remove --force "$wt" 2>/dev/null || true
}

cmd_repos() {
  local dry=0; [ "${1:-}" = "--dry-run" ] && dry=1
  local log="$HOME/.local/state/zenith/golden-rules/$(date -u +%Y%m%d%H%M%S)"; mkdir -p "$log"
  local repos=() d
  # Main checkouts only: a worktree has .git as a file, and ~/.cache copies are never under ~/projects.
  for d in "$PROJECTS"/*/; do d=${d%/}; [ -d "$d/.git" ] && [ -n "$(repo_files "$d")" ] && repos+=("$d"); done
  if [ "$dry" = 1 ]; then printf '%s\n' "${repos[@]}"; return 0; fi
  export -f one_repo; export PARALLEL PROJECTS SRC CONF MDC START END DOCTOC_END BRANCH GEN_RE
  export -f cmd_files apply_block block_ok skip_file repo_files
  export NAMES_STR="${NAMES[*]}"
  printf '%s\n' "${repos[@]}" | xargs -P "$PARALLEL" -I{} bash -c 'NAMES=($NAMES_STR); one_repo "$1"' _ {} | tee "$log/repos.tsv"
  echo "golden-rules: log $log/repos.tsv"
}

# Rebuilds claude/golden-rules.md from the four rule sections of an AGENTS.md (default ~/AGENTS.md), ignoring any
# block already inserted there, so the source follows the owner's file and never its own copy. Owner-run only.
cmd_extract() {
  local from=${1:-$HOME/AGENTS.md}
  # CI and other machines have no ~/AGENTS.md; the committed source is then used as is.
  [ -f "$from" ] || { echo "golden-rules: no $from, keeping $SRC"; return 0; }
  python3 - "$from" "$SRC" <<'PY'
import sys,re
t=open(sys.argv[1]).read()
t=re.sub(r'<!-- GOLDEN-RULES:START -->.*?<!-- GOLDEN-RULES:END -->\n?','',t,flags=re.S).split('\n')
def sec(title):
    i=next(k for k,l in enumerate(t) if l.startswith('## ') and title in l)
    j=next((k for k in range(i+1,len(t)) if t[k].startswith('## ') or t[k].startswith('Zenith Opinions')),len(t))
    return '\n'.join(t[i:j]).rstrip()+'\n'
parts=[sec('Hard rule: Design principles 101'),sec('Hard rule: every Markdown file opens'),sec('Hard rule: herdr tab layout'),sec('Hard rule: the golden system design rules')]
open(sys.argv[2],'w').write('\n'.join(parts))
PY
}

case ${1:-} in
  extract) shift; cmd_extract "$@";;
  write|check) m=$1; shift
    if [ "$#" -eq 0 ]; then root=$(git rev-parse --show-toplevel); set -- $(repo_files "$root"); fi
    cmd_files "$m" "$@";;
  global) shift; cmd_global "$@";;
  repos) shift; cmd_repos "$@";;
  *) sed -n 2,7p "$0"; exit 2;;
esac
