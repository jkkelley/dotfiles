#!/usr/bin/env python3
# name: wiki_review.py
# purpose: Render review pages (design.md + index.html) under review_dir from the newest raw capture of each review.json entry.
# inputs: argv ROOT; <ROOT>/wiki.json (review_dir required), <ROOT>/review.json, <ROOT>/<raw_dir>/*.md, review.html.tmpl beside this file.
# outputs: one line per page on stdout: "WIKI-040 <page dir>"; exit 0 ok, 2 usage, 4 io.
# writes-to: <ROOT>/<review_dir>/<page>/{design.md,index.html,assets}; hand files there are tarred to artifact_new KEY=backup first.
# cleanup: writes are atomic; a hand file is tarred once then removed; a rerun changes nothing.
#
# Design: docs/design/wiki.spec.xml (verb review). Fallback: artifact_new fails -> artifact.sh new, same KEY NAME EXT (FB-004).
import html
import json
import os
import shlex
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import wikilib  # noqa: E402

HERE = Path(__file__).resolve().parent
ARTIFACT_SH = HERE.parent / "artifact" / "artifact.sh"
TEMPLATE = HERE / "review.html.tmpl"


def tilde(path):
    home = str(Path.home())
    s = str(path)
    return "~" + s[len(home):] if s == home or s.startswith(home + os.sep) else s


def store_path(cfg, key, name, ext):
    """Print path from artifact_new; when it fails, the artifact.sh path with the same KEY NAME EXT (FB-004)."""
    cmd = shlex.split(os.path.expanduser(cfg["artifact_new"])) + ["KEY=" + key, "NAME=" + name, "EXT=" + ext]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0 or not r.stdout.strip():
        sys.stderr.write("FB-004 artifact_new failed, using artifact.sh\n")
        r = subprocess.run(["bash", str(ARTIFACT_SH), "new", "--key", key, "--name", name, "--ext", ext],
                           capture_output=True, text=True)
        if r.returncode != 0 or not r.stdout.strip():
            raise OSError("artifact store unavailable: %s" % r.stderr.strip())
    return r.stdout.strip().splitlines()[-1]


def find_assets(key):
    """Files of an artifact key, newest last; a later file of the same name wins. Prefix YYYYMMDD-HHMMSS- is dropped."""
    r = subprocess.run(["bash", str(ARTIFACT_SH), "find", "--key", key], capture_output=True, text=True)
    if r.returncode != 0:
        raise OSError("artifact find %s failed: %s" % (key, r.stderr.strip()))
    out = {}
    for line in r.stdout.splitlines():
        p = Path(line)
        out[p.name[16:] if len(p.name) > 16 and p.name[8] == "-" and p.name[15] == "-" else p.name] = p
    return out


def newest_capture(root, cfg, source):
    """Newest raw capture whose frontmatter source equals `source`; ties by file name. None when there is none."""
    best = None
    for f in sorted((Path(root) / cfg["raw_dir"]).glob("*.md")):
        meta, body = wikilib.read_frontmatter(f.read_text(encoding="utf-8", errors="replace"))
        if meta.get("source") != source:
            continue
        key = (meta.get("captured_at", ""), f.name)
        if best is None or key > best[0]:
            best = (key, f, meta, body)
    return best


def archive_hand_files(cfg, page_dir, written, page):
    """Tar every file under page_dir the script did not write to the store, then remove it. Never removes without the tar."""
    hand = [f for f in sorted(page_dir.rglob("*")) if f.is_file() and f.relative_to(page_dir).as_posix() not in written]
    if not hand:
        return
    tar_path = store_path(cfg, "backup", "wiki-review-" + wikilib.slug(page, 30), "tar")
    with tarfile.open(tar_path, "w") as t:
        for f in hand:
            t.add(str(f), arcname=f.relative_to(page_dir).as_posix())
    with tarfile.open(tar_path) as t:
        if sorted(t.getnames()) != sorted(f.relative_to(page_dir).as_posix() for f in hand):
            raise OSError("backup tar %s does not hold every hand file; nothing removed" % tar_path)
    for f in hand:
        f.unlink()
    for d in sorted((d for d in page_dir.rglob("*") if d.is_dir()), reverse=True):
        if not any(d.iterdir()):
            d.rmdir()
    sys.stderr.write("hand files of %s tarred to %s\n" % (page, tar_path))


def render(root, cfg, entry):
    page, title, source = entry["page"], entry["title"], entry["raw_source"]
    cap = newest_capture(root, cfg, source)
    if cap is None:
        raise OSError("no raw capture for %s (page %s)" % (source, page))
    _, raw_file, meta, body = cap
    if meta.get("blob") and not body.strip():
        body = Path(os.path.expanduser(meta["blob"])).read_text(encoding="utf-8", errors="replace")
    sha12 = meta.get("sha256", "")[:12]
    footer = "generated by make wiki-review from %s/%s sha256 %s" % (cfg["raw_dir"], raw_file.name, sha12)
    page_dir = Path(root) / cfg["review_dir"] / page
    written = {"design.md", "index.html"}
    tmpl = TEMPLATE.read_text(encoding="utf-8")
    page_html = tmpl.replace("@@TITLE@@", html.escape(title)).replace("@@FOOTER@@", html.escape(footer))
    wikilib.atomic_write(page_dir / "design.md", body)
    wikilib.atomic_write(page_dir / "index.html", page_html)
    if entry.get("assets"):
        for name, src in sorted(find_assets(entry["assets"]).items()):
            wikilib.atomic_write(page_dir / name, src.read_bytes())
            written.add(name)
    archive_hand_files(cfg, page_dir, written, page)
    return page_dir


def main(argv):
    if len(argv) != 2:
        sys.stderr.write("usage: wiki_review.py ROOT\n")
        return 2
    root = argv[1]
    try:
        cfg = wikilib.load_config(root)
        if not cfg.get("review_dir"):
            sys.stderr.write("wiki_review: review_dir is not set in wiki.json\n")
            return 2
        rj = Path(root) / "review.json"
        if not rj.is_file():
            sys.stderr.write("wiki_review: no review.json in %s\n" % root)
            return 2
        entries = json.loads(rj.read_text(encoding="utf-8"))
        if isinstance(entries, dict):
            entries = entries.get("entries", [])
        for e in entries:
            for k in ("page", "title", "raw_source"):
                if not e.get(k):
                    sys.stderr.write("wiki_review: review.json entry lacks %s\n" % k)
                    return 2
        for e in entries:
            print("WIKI-040 %s" % render(root, cfg, e))
    except (OSError, ValueError) as e:
        sys.stderr.write("wiki_review: %s\n" % e)
        return 4
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
