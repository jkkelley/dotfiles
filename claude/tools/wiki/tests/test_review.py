#!/usr/bin/env python3
# name: test_review.py
# purpose: Unit tests for wiki_review.py: newest capture wins, rerun is byte identical, hand files are tarred once, assets are copied, FB-004 fallback.
# inputs: none; builds a temp wiki root, a fake artifact_new and an artifact store per test.
# outputs: unittest result on stdout; the last line is OK on success.
# writes-to: a temp directory under the system temp dir, removed after each test.
# cleanup: tearDown removes the temp directory.
import json
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SCRIPT = HERE / "wiki_review.py"
SRC = "~/proj/design.md"


def raw(wiki, name, source, at, body, extra=""):
    (wiki / "raw").mkdir(exist_ok=True)
    (wiki / "raw" / name).write_text("---\nsource: %s\ncaptured_at: %s\nsha256: %s\nbytes: 1\n%s---\n%s" % (
        source, at, (name[:12] * 6)[:64], extra, body))


class ReviewTest(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.wiki = self.tmp / "wiki"
        self.wiki.mkdir()
        self.store = self.tmp / "store"
        self.store.mkdir()
        self.fake = self.tmp / "fake-new.sh"
        self.fake.write_text('#!/bin/sh\necho "%s/${1#KEY=}-${2#NAME=}-$$.${3#EXT=}"\n' % self.store)
        self.fake.chmod(0o755)
        self.config({"review_dir": "review", "artifact_new": str(self.fake)})
        (self.wiki / "review.json").write_text(json.dumps([{"page": "d18", "title": "Design <18>", "raw_source": SRC}]))
        raw(self.wiki, "aaaaaaaaaaaa-design.md", SRC, "2026-10-15T00:00:00Z", "OLD\n")
        raw(self.wiki, "bbbbbbbbbbbb-design.md", SRC, "2026-10-16T00:00:00Z", "NEW\n")
        raw(self.wiki, "cccccccccccc-other.md", "~/proj/other.md", "2026-10-17T00:00:00Z", "OTHER\n")

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def config(self, d):
        (self.wiki / "wiki.json").write_text(json.dumps(d))

    def run_review(self, env=None):
        e = dict(os.environ)
        e.update(env or {})
        return subprocess.run([sys.executable, str(SCRIPT), str(self.wiki)], capture_output=True, text=True, env=e)

    def test_newest_capture_renders_design_and_index(self):
        r = self.run_review()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("WIKI-040", r.stdout)
        page = self.wiki / "review" / "d18"
        self.assertEqual((page / "design.md").read_text(), "NEW\n")
        idx = (page / "index.html").read_text()
        self.assertIn("marked@12.0.2", idx)
        self.assertIn("Design &lt;18&gt;", idx)
        self.assertIn("generated by make wiki-review from raw/bbbbbbbbbbbb-design.md sha256 bbbbbbbbbbbb", idx)

    def test_rerun_is_byte_identical(self):
        self.run_review()
        page = self.wiki / "review" / "d18"
        before = {p.name: p.read_bytes() for p in page.iterdir()}
        r = self.run_review()
        self.assertEqual(r.returncode, 0)
        self.assertEqual(before, {p.name: p.read_bytes() for p in page.iterdir()})

    def test_hand_file_is_tarred_once_then_gone(self):
        page = self.wiki / "review" / "d18"
        (page / "sub").mkdir(parents=True)
        (page / "hand.html").write_text("hand")
        (page / "sub" / "x.txt").write_text("x")
        r = self.run_review()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertFalse((page / "hand.html").exists())
        self.assertFalse((page / "sub").exists())
        tars = list(self.store.glob("backup-*.tar"))
        self.assertEqual(len(tars), 1)
        with tarfile.open(tars[0]) as t:
            self.assertEqual(sorted(t.getnames()), ["hand.html", "sub/x.txt"])
        self.run_review()
        self.assertEqual(len(list(self.store.glob("backup-*.tar"))), 1)

    def test_no_hand_file_makes_no_tar(self):
        self.run_review()
        self.assertEqual(list(self.store.glob("backup-*.tar")), [])

    def test_assets_are_copied_without_timestamp_prefix(self):
        root = self.tmp / "zenith"
        d = root / "images" / "2026" / "10"
        d.mkdir(parents=True)
        (d / "20261016-010101-logo.png").write_bytes(b"PNG")
        (self.wiki / "review.json").write_text(json.dumps(
            [{"page": "d18", "title": "T", "raw_source": SRC, "assets": "images"}]))
        r = self.run_review({"ARTIFACT_ROOT": str(root)})
        self.assertEqual(r.returncode, 0, r.stderr)
        page = self.wiki / "review" / "d18"
        self.assertEqual((page / "logo.png").read_bytes(), b"PNG")
        r = self.run_review({"ARTIFACT_ROOT": str(root)})
        self.assertEqual(list(self.store.glob("backup-*.tar")), [])

    def test_missing_capture_exits_4(self):
        (self.wiki / "review.json").write_text(json.dumps([{"page": "p", "title": "T", "raw_source": "~/nope.md"}]))
        r = self.run_review()
        self.assertEqual(r.returncode, 4)
        self.assertIn("no raw capture", r.stderr)

    def test_no_review_dir_is_usage(self):
        self.config({})
        r = self.run_review()
        self.assertEqual(r.returncode, 2)
        self.assertIn("review_dir", r.stderr)

    def test_artifact_new_failure_uses_artifact_sh(self):
        self.config({"review_dir": "review", "artifact_new": "false"})
        page = self.wiki / "review" / "d18"
        page.mkdir(parents=True)
        (page / "hand.html").write_text("hand")
        root = self.tmp / "zenith"
        r = self.run_review({"ARTIFACT_ROOT": str(root)})
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("FB-004", r.stderr)
        self.assertFalse((page / "hand.html").exists())
        self.assertEqual(len(list((root / "backup").rglob("*.tar"))), 1)


if __name__ == "__main__":
    unittest.main()
