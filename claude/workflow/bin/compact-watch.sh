#!/usr/bin/env bash
# compact-watch.sh <pane> [--once] - keep one seat under its context threshold, hands off.
#
# Runs in the FOREGROUND of a labeled herdr pane. Never started directly: bin/watch-ctl.sh on compact <pane> puts it
# in that pane, so the owner can see it, read it and stop it. It refuses to run outside herdr (dotfiles Rule 18).
#
# Each tick, in order of precedence:
#   hold     changeover-hold in the seat dir: a model switch is in flight. Never fire into it.
#   request  the seat touched compact-request after writing its checkpoint (runbooks/RB-compaction.md). Compact at idle.
#   ceiling  context at or above the ceiling with no request. The seat has not checkpointed and is about to run out.
#            ALERT, then compact with --no-checkpoint - losing some state beats a seat that dies mid-step.
#   nudge    context at or above the threshold with no request. Prompt the seat once per cooldown to finish its step,
#            write its checkpoint and touch the request file. The seat decides where its step ends; the watcher never
#            cuts a step, because a checkpoint taken mid-step describes a state that never existed.
# Why a nudge and not an immediate compaction: bearings-v2 could compact at the threshold because its live state was
# regenerated by a script (checkpoint.sh) on every compaction. A dotfiles seat's state is its own work in flight, which
# only the seat can write down. Rejected: compacting at the threshold unconditionally, which throws that work away.
#
# Log contract (MONITORING-AND-ALERTING v1.0.0): one line on change only; ALERT only for the owner's decision.
# BREADCRUMB - `set -uo pipefail`, deliberately no -e: a tick is built from checks expected to fail most of the time.
#   Under -e the first expected non-match kills the loop silently. Same reasoning as bin/workflow-watch.sh.
set -uo pipefail
# shellcheck source=bin/workflow-lib.sh disable=SC1091
. "$(dirname "$(readlink -f "$0")")/workflow-lib.sh"
wf_need jq

pane=""; once=0
for a in "$@"; do case "$a" in --once) once=1 ;; -*) wf_die "unknown flag $a" ;; *) pane="$a" ;; esac; done
[ -n "$pane" ] || wf_die "usage: compact-watch.sh <pane> [--once]"
[ "${HERDR_ENV:-}" = 1 ] || wf_die "refusing to run outside a herdr pane (dotfiles Rule 18); use bin/watch-ctl.sh on compact $pane"

BIN="$(dirname "$(readlink -f "$0")")"
seat="$(wf_seat_dir "$pane")"
# The threshold is read from the compaction declaration's agent spec and never defaulted here: the watcher-state schema
# says so, because a threshold a script carries a default for is a threshold nobody can see changing.
AT="$("$BIN/workflow-spec.sh" compaction | jq -er .context_threshold_percent)" || wf_die "compaction spec carries no threshold"
CEIL="$(wf_cfg '.workflow.compaction.ceiling_percent // 85')"
COOL="$(wf_cfg '.workflow.compaction.cooldown_seconds // 900')"
IDLE="$(wf_cfg '.workflow.watchers.idle_seconds // 45')"
TICK="$(wf_cfg '.workflow.compaction.tick_seconds // 30')"
WF_WATCH_LOG="$seat/compact-watch.log"; WF_WATCH_INTERVAL="$TICK"; WF_WATCH_STARTED="$(wf_now)"
export WF_WATCH_LOG WF_WATCH_INTERVAL WF_WATCH_STARTED
echo "$$" > "$seat/compact-watch.pid"
trap 'rm -f "$seat/compact-watch.pid"; wf_watch_log "watch: stopped"; wf_watch_state compact-watch off 0' EXIT
wf_watch_state compact-watch on "$$" "$(jq -n --arg p "$pane" --argjson t "$AT" --argjson i "$IDLE" \
  '{watches_workflow:"compaction", context_threshold_percent:$t, idle_seconds:$i, pane:$p}')"
wf_watch_log "watch: started pane=$pane at=$AT ceiling=$CEIL idle=$IDLE cooldown=$COOL"

since() { local f="$1"; [ -f "$f" ] || { printf 999999; return; }; printf '%s' $(( $(date -u +%s) - $(cat "$f") )); }

tick() {
  local tr pct req idle
  tr="$(wf_transcript "$pane")" || { wf_watch_change state "seat: no agent transcript for $pane"; return; }
  pct="$(wf_context_pct "$tr")"; idle="$(wf_idle_seconds "$tr")"
  req=0; [ -f "$seat/compact-request" ] && req=1
  if [ -f "$seat/changeover-hold" ]; then wf_watch_change state "hold: model changeover in progress at ${pct}%"; return; fi
  if [ "$req" = 1 ]; then
    [ "$(since "$seat/.last-compact")" -ge "$COOL" ] || { wf_watch_change state "cooldown: request pending"; return; }
    [ "$idle" -ge "$IDLE" ] || { wf_watch_change state "request: waiting for idle at ${pct}%"; return; }
    wf_watch_change state "fire: seat requested compaction at ${pct}%"
    date -u +%s > "$seat/.last-compact"; rm -f "$seat/compact-request"
    if "$BIN/compact-now.sh" "$pane" >/dev/null 2>&1; then wf_watch_log "compact: ok, $(readlink -f "$seat/ceremony-compact.md")"
    else wf_watch_log "ALERT compaction failed for $pane; not retrying; read $seat/compact.log"; fi
    return
  fi
  if [ "$pct" -ge "$CEIL" ]; then
    [ "$(since "$seat/.last-compact")" -ge "$COOL" ] || { wf_watch_change state "cooldown: at ceiling ${pct}%"; return; }
    [ "$idle" -ge "$IDLE" ] || { wf_watch_change state "ceiling: ${pct}%, waiting for idle"; return; }
    wf_watch_log "ALERT $pane at ${pct}% with no checkpoint request; compacting without a checkpoint"
    date -u +%s > "$seat/.last-compact"
    "$BIN/compact-now.sh" "$pane" --no-checkpoint >/dev/null 2>&1 \
      || wf_watch_log "ALERT ceiling compaction failed for $pane; not retrying; read $seat/compact.log"
    return
  fi
  if [ "$pct" -ge "$AT" ]; then
    if [ "$(since "$seat/.last-nudge")" -ge "$COOL" ] && [ "$idle" -ge "$IDLE" ]; then
      date -u +%s > "$seat/.last-nudge"
      if herdr agent prompt "$pane" "Context is at ${pct} percent, at or over your ${AT} percent threshold. Finish the step you are on, then follow ${WF_REPO}/runbooks/RB-compaction.md: write your checkpoint into ${seat}, then touch ${seat}/compact-request and end your turn. The watcher compacts you at idle. Never send /compact yourself." >/dev/null 2>&1; then
        wf_watch_log "nudge: $pane at ${pct}%, asked to checkpoint"
      else wf_watch_log "ALERT could not prompt $pane; is herdr up?"; fi
    elif [ -f "$seat/.last-nudge" ]; then wf_watch_change state "threshold: ${pct}%, nudged, waiting for the seat's request"
    else wf_watch_change state "threshold: ${pct}%, waiting for the seat to go idle before nudging"; fi
    return
  fi
  wf_watch_change state "ok: ${pct}%"
}

while :; do
  tick
  [ "$once" = 1 ] && exit 0
  sleep "$TICK"
done
